create extension if not exists pgcrypto;

create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 student_code text unique,
 created_at timestamptz not null default now()
);
create table if not exists public.notes (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 content text not null,
 created_at timestamptz not null default now()
);
create table if not exists public.subjects (
 id bigint generated by default as identity primary key,
 name text not null,
 code text,
 link text,
 icon text,
 image_url text,
 video_url text,
 department text,
 year_level text,
 term text,
 created_at timestamptz not null default now()
);
create table if not exists public.quizzes (
 id bigint generated by default as identity primary key,
 title text not null,
 subject_code text,
 description text,
 video_url text,
 time_limit integer not null default 20,
 is_active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.questions (
 id bigint generated by default as identity primary key,
 quiz_id bigint not null references public.quizzes(id) on delete cascade,
 question_text text not null,
 question_type text not null default 'multiple_choice',
 option_1 text,
 option_2 text,
 option_3 text,
 option_4 text,
 correct_option integer,
 explanation text,
 image_url text,
 created_at timestamptz not null default now()
);
create table if not exists public.quiz_results (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 quiz_id bigint references public.quizzes(id) on delete set null,
 student_name text,
 quiz_title text,
 score integer not null default 0,
 total_score integer not null default 0,
 created_at timestamptz not null default now()
);
create table if not exists public.news (
 id bigint generated by default as identity primary key,
 content text not null,
 created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.notes enable row level security;
alter table public.subjects enable row level security;
alter table public.quizzes enable row level security;
alter table public.questions enable row level security;
alter table public.quiz_results enable row level security;
alter table public.news enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated using (auth.uid() = id);
drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "notes_manage_own" on public.notes;
create policy "notes_manage_own" on public.notes for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "subjects_read_public" on public.subjects;
create policy "subjects_read_public" on public.subjects for select to anon, authenticated using (true);
drop policy if exists "quizzes_read_public" on public.quizzes;
create policy "quizzes_read_public" on public.quizzes for select to anon, authenticated using (is_active = true);
drop policy if exists "questions_read_public" on public.questions;
create policy "questions_read_public" on public.questions for select to anon, authenticated using (exists (select 1 from public.quizzes q where q.id = quiz_id and q.is_active = true));
drop policy if exists "results_read_own" on public.quiz_results;
create policy "results_read_own" on public.quiz_results for select to authenticated using (auth.uid() = user_id);
drop policy if exists "results_insert_own" on public.quiz_results;
create policy "results_insert_own" on public.quiz_results for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "news_read_public" on public.news;
create policy "news_read_public" on public.news for select to anon, authenticated using (true);

create index if not exists notes_user_created_idx on public.notes(user_id, created_at desc);
create index if not exists results_user_created_idx on public.quiz_results(user_id, created_at desc);
create index if not exists questions_quiz_idx on public.questions(quiz_id);
create index if not exists subjects_filters_idx on public.subjects(year_level, department, term);
